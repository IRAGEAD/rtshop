def _base(ko, table):
    m = re.match(r'^(.+) 선행 퀘스트 \((\d)/7\)$', ko)
    if m: return "%s Prerequisite Quest (%s/7)" % (JOBS[m.group(1)], m.group(2))
    m = re.match(r'^초보 모험가의 길 \((\d)/4\)$', ko)
    if m: return "The Novice Adventurer's Road (%s/4)" % m.group(1)
    if ko.endswith(' 에게 말을 걸어라.'): return "Talk to %s." % NPCS[ko[:-len(' 에게 말을 걸어라.')]]
    tail = ' 을(를) 만났군. 이제 그 사람의 시험을 받아 보게.'
    if ko.endswith(tail): return "So you've met %s. Now take the test they set you." % NPCS[ko[:-len(tail)]]
    return table[ko]


def _build():
    here = os.path.dirname(os.path.abspath(__file__))
    src = json.load(open(os.path.join(os.path.dirname(here), 'source2.json'), encoding='utf-8'))[START:]
    bases, hints = [], []
    for s in src:
        parts = s.split('\n')
        if not re.match(r'^.+ 선행 퀘스트 \(\d/7\)$', parts[0]) and not re.match(r'^초보 모험가의 길 \(\d/4\)$', parts[0]) \
                and not parts[0].endswith(' 에게 말을 걸어라.') and not parts[0].endswith(' 을(를) 만났군. 이제 그 사람의 시험을 받아 보게.') and parts[0] not in bases:
            bases.append(parts[0])
        for h in parts[1:]:
            if h not in hints: hints.append(h)
    if len(bases) != len(BASE) or len(hints) != len(HINTS):
        raise SystemExit("p409: 본문 %d/%d, 도움말 %d/%d — 원문이 바뀌었습니다" % (len(BASE), len(bases), len(HINTS), len(hints)))
    for ko, en in zip(hints, HINTS):   # 머리표와 키 표시가 그대로인지
        if ko.split(']')[0] != en.split(']')[0] or sorted(re.findall(r'\{key:[^}]+\}', ko)) != sorted(re.findall(r'\{key:[^}]+\}', en)):
            raise SystemExit("p409: 도움말의 표시가 원문과 다릅니다: " + ko[:40])
    bt, ht = dict(zip(bases, BASE)), dict(zip(hints, HINTS))
    out = []
    for s in src:
        parts = s.split('\n')
        out.append('\n'.join([_base(parts[0], bt)] + [ht[h] for h in parts[1:]]))
    return out


EN = _build()
