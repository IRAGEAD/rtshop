def grid(name):
    rows = [r for r in I[name].strip('\n').split('\n')]
    rows = [r.replace('к', 'k') for r in rows]
    assert len(rows) == 11, (name, len(rows))
    for r in rows: assert len(r) == 11, (name, r, len(r))
    return rows

def png(name):
    im = Image.new('RGBA', (11, 11), (0, 0, 0, 0))
    for y, r in enumerate(grid(name)):
        for x, ch in enumerate(r):
            c = PAL[ch]
            if c: im.putpixel((x, y), c + (255,))
    return im

