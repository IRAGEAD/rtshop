        d = ImageDraw.Draw(sheet)
        for i, n in enumerate(I):
            cx, cy = (i % cols) * 13 * S, (i // cols) * 15 * S
            d.ellipse([cx + S * 0.5, cy + S * 0.5, cx + S * 12.5, cy + S * 12.5], fill=(236, 146, 56, 255), outline=(30, 26, 22, 255), width=S // 2)
