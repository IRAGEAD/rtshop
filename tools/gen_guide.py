CATS = []


def cat(id_, name):
    c = {"id": id_, "name": name, "pages": []}
    CATS.append(c)
    return c


def page(c, id_, title, text, image="", icons=None, mod="", keys=""):
    p = {"id": id_, "title": title, "text": text.strip("\n")}
    if image:
        p["image"] = "rtshop:textures/guide/%s.png" % image
        p["iw"], p["ih"] = 480, 270
    if icons: p["icons"] = icons
    if mod: p["mod"] = mod
    if keys: p["keys"] = keys
    c["pages"].append(p)


