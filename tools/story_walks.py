# 규칙 (Companions.java 와 짝):
#   arrive : 그 퀘스트에서 한 번만 한다. 반드시 "그 장소"에 대한 말일 것.
#   spot   : {흔적 ID: 한마디}. 그 흔적이 나타났을 때 한 번만. 흔적마다 따로 쓴다 (없으면 말하지 않는다).
#   idle   : 오래 서 있을 때의 혼잣말. 줄마다 한 번만, 2분 반에 하나. 많아야 둘. 버릇(장갑·신발 끈·수첩)은 장 전체에서 한두 번만 쓴다.
#   done   : 그 자리에서 할 일을 다 했을 때 한 번.
#   fight / low : 인물마다 한 벌 (VOICE). 싸움 외침은 90초에 한 번, 같은 줄을 잇달아 하지 않는다.
