def draw(art):
    rows = [r for r in art.strip('\n').split('\n')]
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            c = PAL.get(ch)
            if c: px[x, y] = c + (255,)
    return im


def main():
    prev = sys.argv[1] if len(sys.argv) > 1 else None
    made = {}
    for (name, v), art in ICONS.items():
        made[(name, v)] = draw(art)
    for name, v in CHOSEN.items():
        made[(name, v)].save(os.path.join(OUT, name + '.png'))
    if prev:
        os.makedirs(prev, exist_ok=True)
        S = 12
        W, H = 3 * (16 * S + 70) + 40, 2 * (16 * S + 70) + 30
        sheet = Image.new('RGB', (W, H), (54, 48, 44))
        d = ImageDraw.Draw(sheet)
        try:
            font = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', 22)
        except Exception:
            font = ImageFont.load_default()
        titles = {'forger_kit': '위조 도구 꾸러미', 'appraisal_loupe': '감정 돋보기'}
        for r, name in enumerate(['forger_kit', 'appraisal_loupe']):
            for c, v in enumerate('ABC'):
                x, y = 40 + c * (16 * S + 70), 20 + r * (16 * S + 70)
                bg = Image.new('RGB', (16 * S, 16 * S), (139, 139, 139))
                ic = made[(name, v)].resize((16 * S, 16 * S), Image.NEAREST)
                bg.paste(ic, (0, 0), ic)
                sheet.paste(bg, (x, y + 34))
                label = '%s %s%s' % (titles[name], v, '  (기본)' if CHOSEN[name] == v else '')
                d.text((x, y + 4), label, fill=(240, 226, 190), font=font)
        sheet.save(os.path.join(prev, 'forgery_choices.png'))
        print('preview ->', os.path.join(prev, 'forgery_choices.png'))


if __name__ == '__main__':
    main()
